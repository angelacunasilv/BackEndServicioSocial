CREATE TABLE usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identificador varchar(32) NOT NULL UNIQUE,
  nombre_completo varchar(221) NOT NULL,
  correo varchar(254) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  rol varchar(3) NOT NULL CHECK (rol IN ('ALU', 'JSS', 'JDV', 'ADM')),
  activo boolean NOT NULL DEFAULT true,
  version_sesion integer NOT NULL DEFAULT 1,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE personal (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id),
  departamento varchar(120)
);
CREATE TABLE alumnos (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id),
  nombre varchar(221) NOT NULL,
  apellidos varchar(221) NOT NULL DEFAULT '',
  carrera varchar(120),
  semestre integer CHECK (semestre BETWEEN 1 AND 20),
  telefono varchar(24),
  plan_estudios varchar(120),
  curso_induccion_acreditado boolean NOT NULL DEFAULT false
);
CREATE TABLE sesiones (
  sid varchar PRIMARY KEY,
  sess json NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX sesiones_expire ON sesiones(expire);
CREATE TABLE recuperaciones (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id),
  hash char(64) NOT NULL UNIQUE,
  vence_en timestamptz NOT NULL
);
CREATE TABLE cursos_induccion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_curso date NOT NULL,
  periodo varchar(32) NOT NULL,
  codigo_qr uuid NOT NULL UNIQUE,
  creado_por integer NOT NULL REFERENCES usuarios(id),
  UNIQUE (periodo, fecha_curso)
);
CREATE TABLE asistencias_induccion (
  curso_id integer REFERENCES cursos_induccion(id),
  alumno_id integer REFERENCES alumnos(usuario_id),
  PRIMARY KEY (curso_id, alumno_id)
);
CREATE TABLE programas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo varchar(8) NOT NULL CHECK (tipo IN ('INTERNO', 'EXTERNO')),
  creado_por integer NOT NULL REFERENCES usuarios(id),
  nombre_proyecto varchar(200) NOT NULL,
  area varchar(160) NOT NULL,
  nombre_titular varchar(160) NOT NULL,
  puesto_titular varchar(160) NOT NULL,
  nombre_responsable varchar(160) NOT NULL,
  puesto_responsable varchar(160) NOT NULL,
  actividades text NOT NULL,
  telefono varchar(24) NOT NULL,
  correo varchar(254) NOT NULL,
  domicilio varchar(300) NOT NULL,
  periodo varchar(32) NOT NULL,
  objetivo text,
  horario varchar(160),
  cupo integer,
  cupo_disponible integer,
  activo boolean NOT NULL DEFAULT true,
  estado varchar(9) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO')),
  observaciones text,
  archivo_pdf bytea,
  revisado_por integer REFERENCES usuarios(id),
  fecha_revision timestamptz,
  fecha_envio timestamptz NOT NULL DEFAULT now(),
  CHECK (estado <> 'RECHAZADO' OR NULLIF(btrim(observaciones), '') IS NOT NULL),
  CHECK (
    (tipo = 'INTERNO' AND cupo IS NOT NULL AND cupo > 0 AND cupo_disponible IS NOT NULL
      AND cupo_disponible BETWEEN 0 AND cupo AND objetivo IS NOT NULL AND horario IS NOT NULL AND estado = 'ACEPTADO')
    OR (tipo = 'EXTERNO' AND cupo IS NULL AND cupo_disponible IS NULL)
  )
);
CREATE INDEX programas_banco ON programas(tipo, activo, periodo, id);
CREATE INDEX programas_revision ON programas(tipo, estado, id);
CREATE INDEX programas_autor ON programas(creado_por, id DESC);
CREATE UNIQUE INDEX programas_externo_pendiente ON programas(creado_por)
  WHERE tipo = 'EXTERNO' AND estado = 'PENDIENTE';
CREATE TABLE expedientes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alumno_id integer NOT NULL UNIQUE REFERENCES alumnos(usuario_id),
  programa_id integer NOT NULL REFERENCES programas(id),
  avance_horas integer NOT NULL DEFAULT 0 CHECK (avance_horas >= 0),
  porcentaje_avance numeric(5,2) NOT NULL DEFAULT 0 CHECK (porcentaje_avance BETWEEN 0 AND 100),
  estado_global varchar(10) NOT NULL DEFAULT 'INSCRITO' CHECK (estado_global IN ('INSCRITO', 'TERMINADO')),
  fecha_inscripcion timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX expedientes_programa ON expedientes(programa_id);
CREATE TABLE documentos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expediente_id integer NOT NULL REFERENCES expedientes(id),
  tipo varchar(20) NOT NULL CHECK (tipo IN ('SOLICITUD', 'CARTA_ACEPTACION', 'REPORTE_BIMESTRAL', 'REPORTE_FINAL', 'CARTA_TERMINACION')),
  numero_reporte integer NOT NULL DEFAULT 0,
  horas integer CHECK (horas BETWEEN 0 AND 10000),
  nombre_archivo varchar(255) NOT NULL,
  archivo_pdf bytea NOT NULL,
  extension varchar(4) NOT NULL DEFAULT '.pdf' CHECK (extension = '.pdf'),
  tamano integer NOT NULL CHECK (tamano > 0 AND tamano <= 10485760),
  vigente boolean NOT NULL DEFAULT true,
  estado varchar(9) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO')),
  observaciones text,
  fecha_subida timestamptz NOT NULL DEFAULT now(),
  fecha_validacion timestamptz,
  revisado_por integer REFERENCES usuarios(id),
  CHECK (estado <> 'RECHAZADO' OR NULLIF(btrim(observaciones), '') IS NOT NULL),
  CHECK ((tipo = 'REPORTE_BIMESTRAL' AND numero_reporte BETWEEN 1 AND 3)
    OR (tipo <> 'REPORTE_BIMESTRAL' AND numero_reporte = 0)),
  CHECK ((tipo IN ('REPORTE_BIMESTRAL', 'REPORTE_FINAL')) = (horas IS NOT NULL))
);
CREATE INDEX documentos_expediente ON documentos(expediente_id, id DESC);
CREATE INDEX documentos_revision ON documentos(estado, id) WHERE vigente;
CREATE UNIQUE INDEX documentos_entrega_vigente ON documentos(expediente_id, tipo, numero_reporte) WHERE vigente;
CREATE TABLE plantillas (
  tipo varchar(20) PRIMARY KEY CHECK (tipo IN ('SOLICITUD', 'CARTA_ACEPTACION', 'REPORTE_BIMESTRAL', 'REPORTE_FINAL', 'CARTA_TERMINACION')),
  archivo_pdf bytea NOT NULL,
  actualizado_por integer NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE constancias_terminacion (
  folio uuid PRIMARY KEY,
  expediente_id integer NOT NULL UNIQUE REFERENCES expedientes(id),
  emitida_por integer NOT NULL REFERENCES usuarios(id),
  fecha_emision timestamptz NOT NULL DEFAULT now(),
  firmado boolean NOT NULL DEFAULT false,
  archivo_pdf bytea NOT NULL
);
